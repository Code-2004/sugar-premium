// Indian Numbering Helper (strictly in INR Crores & Lakhs)
export function formatIndianCurrency(amountInINR) {
  if (amountInINR >= 10000000) {
    const cr = (amountInINR / 10000000).toFixed(2);
    return `₹${cr} Cr`;
  } else if (amountInINR >= 100000) {
    const lk = (amountInINR / 100000).toFixed(2);
    return `₹${lk} Lakh`;
  } else {
    return `₹${amountInINR.toLocaleString('en-IN')}`;
  }
}
